const SUPER_AGENT_KEYWORDS =
  /shark|ruthless|hardball|power ?broker|maverick|fixer|dealmaker|corporate|mogul|last-minute|provocateur|unlimited|brand/i;
const FAMILY_KEYWORDS = /family|loyal|community|patriarch|humble|protector|grassroots|honest|ethical/i;
const MENTOR_KEYWORDS = /mentor|tactic|strateg|analy|data|scout|guide|academy|measured/i;

/**
 * Deterministically maps a catalogue agent onto a hireable archetype.
 * Personality keywords decide first; numeric traits break ties.
 * A missing agent (fired / never hired) is self-represented.
 */
export function archetypeForAgent(
  agent: Pick<PlayerAgent, "personality" | "commission" | "loyaltyRisk"> & { archetype?: string } | null | undefined,
): AgentArchetypeKey {
  if (!agent) return "self_represented";
  if (agent.archetype && agent.archetype in AGENT_ARCHETYPES) return agent.archetype as AgentArchetypeKey;
  const personality = agent.personality || "";
  if (SUPER_AGENT_KEYWORDS.test(personality)) return "super_agent";
  if (FAMILY_KEYWORDS.test(personality)) return "family_relative";
  if (MENTOR_KEYWORDS.test(personality)) return "tactical_mentor";
  if ((agent.commission ?? 0) >= 9 || (agent.loyaltyRisk ?? 0) >= 7) return "super_agent";
  if ((agent.commission ?? 0) <= 5) return "family_relative";
  return "tactical_mentor";
}

/** Catalogue commission clamped into the archetype's band (0 when self-represented). */
export function getEffectiveCommission(agent: PlayerAgent | null | undefined): number {
  const arch = AGENT_ARCHETYPES[archetypeForAgent(agent)];
  const base = agent ? agent.commission : 0;
  return Math.max(arch.commissionRange[0], Math.min(arch.commissionRange[1], base));
}
