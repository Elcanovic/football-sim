export function getDefaultAgentForNationality(iso?: string): PlayerAgent {
  const normIso = (iso || "ar").toLowerCase();
  const match = AGENTS_CATALOG.find((a) => a.iso === normIso);
  if (match) return match;
  if (normIso === "ar") return AGENTS_CATALOG.find((a) => a.id === "agent-arg-perez") ?? AGENTS_CATALOG[0];
  if (normIso === "az") return AGENTS_CATALOG.find((a) => a.id === "agent-aze-mammadov") ?? AGENTS_CATALOG[0];
  return AGENTS_CATALOG[0];
}

export function calculateAgentNegotiatedWage(baseWage: number, agent?: PlayerAgent | null): number {
  if (!agent) return baseWage;
  const boostPct = 0.05 + ((agent.negotiation || 5) * 0.035);
  return Math.round(baseWage * (1 + boostPct));
}

